locations = ['United Kingdom', 'United States of America', 'Ireland', 'China', 'Japan']

print("Original list: ")
print(locations)

print("Sorted list: ")
print(sorted(locations))

print("Original list: ")
print(locations)

print("\nSorted list(reverse): ")
print(sorted(locations, reverse=True))

print("Original list: ")
print(locations)

print("\nSorted list(reverse): ")
locations.reverse()
print(locations)

print("\nSorted list(reverse): ")
locations.reverse()
print(locations)

print("\nSorted list(sort): ")
locations.sort()
print(locations)

print("\nSorted list(sort): ")
locations.sort(reverse=True)
print(locations)